"""
Alert and Evidence models for SentinelWatch Backend.
"""

import enum
import uuid
from datetime import datetime, timezone
from typing import Optional

from sqlalchemy import DateTime, Enum, ForeignKey, Index, Integer, String, Text, func
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from sentinelwatch_backend.models.base import Base


class AlertSeverity(str, enum.Enum):
    """Alert severity levels."""
    CRITICAL = "critical"
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"
    INFO = "info"


class AlertStatus(str, enum.Enum):
    """Alert triage status."""
    NEW = "new"
    INVESTIGATING = "investigating"
    TRUE_POSITIVE = "true_positive"
    FALSE_POSITIVE = "false_positive"
    BENIGN = "benign"
    RESOLVED = "resolved"
    SUPPRESSED = "suppressed"


class Alert(Base):
    """Security alert generated by detection engine."""
    __tablename__ = "alerts"

    id: Mapped[str] = mapped_column(
        String(36), primary_key=True, default=lambda: str(uuid.uuid4())
    )

    # Agent and rule association
    agent_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("agents.id", ondelete="CASCADE"), nullable=False, index=True
    )
    rule_id: Mapped[Optional[str]] = mapped_column(String(255), nullable=True, index=True)
    rule_name: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)

    # Alert details
    severity: Mapped[str] = mapped_column(String(20), nullable=False, index=True)
    status: Mapped[str] = mapped_column(String(20), nullable=False, index=True)

    # MITRE ATT&CK mapping
    mitre_techniques: Mapped[Optional[list]] = mapped_column(JSONB, nullable=True)
    mitre_tactics: Mapped[Optional[list]] = mapped_column(JSONB, nullable=True)

    # Correlation
    correlation_key: Mapped[Optional[str]] = mapped_column(String(255), nullable=True, index=True)
    correlation_id: Mapped[Optional[str]] = mapped_column(String(64), nullable=True, index=True)
    finding_count: Mapped[int] = mapped_column(Integer, default=1, nullable=False)

    # Deduplication
    dedup_key: Mapped[Optional[str]] = mapped_column(String(64), nullable=True, index=True)
    dedup_window_seconds: Mapped[int] = mapped_column(Integer, default=3600, nullable=False)

    # Summary and description
    summary: Mapped[str] = mapped_column(String, nullable=False)
    description: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Evidence reference
    evidence_id: Mapped[Optional[str]] = mapped_column(String(36), nullable=True, index=True)

    # Triage
    assignee: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)
    triage_notes: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    triaged_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)

    # Resolution
    resolution: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)  # true_positive, false_positive, etc.
    resolution_notes: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    resolved_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    resolved_by: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)

    # Timestamps
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), nullable=False, index=True
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
        nullable=False,
    )
    deleted_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True, index=True)

    # Relationships
    agent = relationship("Agent", back_populates="alerts")
    evidence = relationship("Evidence", back_populates="alert", uselist=False)

    __table_args__ = (
        Index("ix_alerts_agent_status", "agent_id", "status"),
        Index("ix_alerts_severity_created", "severity", "created_at"),
        Index("ix_alerts_correlation", "correlation_key"),
    )

    def __repr__(self) -> str:
        return f"<Alert(id={self.id}, severity={self.severity}, status={self.status})>"


class Evidence(Base):
    """Raw telemetry evidence linked to alerts."""
    __tablename__ = "evidence"

    id: Mapped[str] = mapped_column(
        String(36), primary_key=True, default=lambda: str(uuid.uuid4())
    )

    alert_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("alerts.id", ondelete="CASCADE"), nullable=False, unique=True, index=True
    )

    # Telemetry type that triggered the alert
    telemetry_type: Mapped[str] = mapped_column(String(50), nullable=False)  # process, service, startup, eventlog

    # Raw telemetry records (JSON array)
    raw_records: Mapped[list] = mapped_column(JSONB, nullable=False)

    # Enrichment data
    process_tree: Mapped[Optional[list]] = mapped_column(JSONB, nullable=True)
    network_connections: Mapped[Optional[list]] = mapped_column(JSONB, nullable=True)
    file_hashes: Mapped[Optional[dict]] = mapped_column(JSONB, nullable=True)
    threat_intel: Mapped[Optional[dict]] = mapped_column(JSONB, nullable=True)

    # Metadata
    collected_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), nullable=False
    )
    size_bytes: Mapped[int] = mapped_column(Integer, default=0, nullable=False)

    # Relationships
    alert = relationship("Alert", back_populates="evidence")

    def __repr__(self) -> str:
        return f"<Evidence(id={self.id}, alert={self.alert_id}, type={self.telemetry_type})>"
